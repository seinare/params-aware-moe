#!/usr/bin/env bash
set -euo pipefail
ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT_DIR"
PYTHON_BIN="${PYTHON_BIN:-.venv/bin/python}"
COMMON="CUDA_VISIBLE_DEVICES=0,1 WANDB_PROJECT=params-aware-moe DATA_PATH=data/datasets/finewebedu10B_sp1024 TOKENIZER_PATH=data/tokenizers/fineweb_1024_bpe.model VOCAB_SIZE=1024 TRAIN_SEQ_LEN=1024 TRAIN_BATCH_TOKENS=524288 VAL_BATCH_SIZE=8192 VAL_MAX_TOKENS=4194304 ITERATIONS=19073 WARMUP_STEPS=20 WARMDOWN_ITERS=0 MAX_WALLCLOCK_SECONDS=0 ROUTE_METRICS=1 MUON_3D_IMPL=batched MUON_REDUCE_UPDATES=1 SKIP_FINAL_EVAL=0 SKIP_POST_TRAINING_EVAL=1 FINAL_FULL_VAL=1 SAVE_CHECKPOINT=1 CHECKPOINT_DIR=checkpoint/ddp_10b TRAIN_LOG_EVERY=100 VAL_LOSS_EVERY=0 NUM_LAYERS=8 MODEL_DIM=512 NUM_HEADS=8 NUM_KV_HEADS=4 MLP_ACTIVATION=relu_square USE_DENSE_MLP_RESIDUAL=0 ROUTER_AUX_LOSS_COEF=0 USE_PARAM_AWARE_MOE=1 MOE_ROUTER_TYPE=param MOE_TOP_K=16 EXPERT_INNER_DIM=64 ROUTER_M=4 ROUTER_PRODUCT_DIM=256 SHARE_ROUTER_KEY_PROJ=1 ROUTER_KEY_DETACH=1 NUM_MLP_POOLS=8 USE_EXPERT_PARALLEL=0 COMPILE_MODEL=1 COMPILE_FULLGRAPH=1"
run_pa() {
  name="$1"; experts="$2"
  log="logs/run10b_${name}_$(date +%Y%m%d_%H%M%S).log"
  echo "===== RUN $name experts=$experts pdim=256 lb=0 log=$log ====="
  env $COMMON WANDB_RUN_NAME="ddp10b_${name}" NUM_EXPERTS="$experts" "$PYTHON_BIN" -m torch.distributed.run --standalone --nproc_per_node=2 train_gpt.py 2>&1 | tee "$log"
}
run_pa pa_e64k16_pd256_lb0 64
run_pa pa_e128k16_pd256_lb0 128
run_pa pa_e256k16_pd256_lb0 256
